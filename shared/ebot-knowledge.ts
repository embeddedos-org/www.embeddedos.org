/**
 * eBot's answers, and the matcher that picks one.
 *
 * eBot used to POST every message to `/api/trpc/ebot.chat`, which called an LLM
 * through `forge.manus.im`. Two things were wrong with that in production. The
 * site deploys as a prerendered static build to cPanel — `.cpanel.yml` copies
 * files into the document root and starts no process — so the endpoint answered
 * 404 with the 404 HTML page and the browser reported
 * `Unexpected token '<', "<!DOCTYPE "... is not valid JSON`. Every visitor who
 * opened the chat got "Sorry, I'm having trouble connecting right now."
 * Separately, that host is a sandbox proxy that would not have authenticated
 * from this account even with a server running.
 *
 * So eBot answers from here instead: a fixed set of topics, matched in the
 * browser. No network call, no API key, nothing to expire, and it cannot fail
 * while the page itself is loading.
 *
 * The trade is that eBot only knows what is written here. That is deliberate —
 * every figure below resolves to `shared/stack-data.ts` (regenerated by
 * `pnpm sync:stack` from the source repositories) or to
 * `client/src/data/foundation.ts` (transcribed from the IRS determination), so
 * eBot cannot state a number the rest of the site contradicts. The retired
 * "52+ platforms" figure was still being asserted by the old system prompt long
 * after the pages had moved to the counted figure of 83 boards.
 *
 * When nothing matches, eBot says so and offers the search index rather than
 * guessing. An assistant that invents an answer about medical hardware or
 * charitable status is worse than one that admits the gap.
 */
import { STACK } from "./stack-data";
import { searchSite } from "./site-index";

/** A link eBot can offer alongside an answer. */
export type KnowledgeLink = {
  label: string;
  /** Site route, or an absolute URL for anything off-site. */
  href: string;
};

/** One thing eBot knows how to answer. */
export type Topic = {
  id: string;
  /**
   * Phrases that select this topic. Multi-word phrases score higher than single
   * words, so "get started" beats a passing mention of "start".
   */
  patterns: string[];
  /** The reply, in the small markdown subset `EBot.tsx` renders. */
  answer: string;
  links?: KnowledgeLink[];
};

/** What `answerQuestion` returns. */
export type Answer = {
  reply: string;
  links: KnowledgeLink[];
  /**
   * How the reply was produced. `topic` is a curated answer, `search` is a
   * pointer to matching pages, `unknown` is an admitted gap. Exposed so the UI —
   * and the tests — can tell a real answer from a fallback.
   */
  kind: "topic" | "search" | "unknown";
};

