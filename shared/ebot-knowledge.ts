/**
 * Score one topic against a normalised question.
 *
 * A multi-word pattern is worth far more than a single word, because a phrase
 * hit ("get started") is strong evidence of intent while a bare word ("start")
 * often appears by accident. Word-boundary matching keeps "ai" out of "chair"
 * and "opt" out of "option".
 */
const scoreTopic = (topic: Topic, q: string): number => {
  let score = 0;
  for (const pattern of topic.patterns) {
    if (pattern.includes(" ")) {
      if (q.includes(pattern)) score += 10 + pattern.length / 10;
    } else if (new RegExp(`\\b${escapeRegExp(pattern)}\\b`).test(q)) {
      score += 3;
    }
  }
  return score;
};

/** Escape a pattern for literal use inside a RegExp. */
const escapeRegExp = (s: string): string =>
  s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/**
 * Strip punctuation and collapse whitespace so patterns match plain prose.
 *
 * Removes a known punctuation set rather than keeping a known letter set: the
 * project compiles without an explicit `target`, so the unicode-property regex
 * flag needed for `\p{L}` is unavailable, and an ASCII-only whitelist would
 * shred accented words into fragments. Hyphens survive because board and
 * product names contain them ("risc-v", "health-ring", "as-10").
 */
const normalise = (question: string): string =>
  question
    .toLowerCase()
    .replace(/[.,/#!$%^&*;:{}=~()?"'`|<>+[\]\\@_‘’“”]/g, " ")
    .replace(/\s+/g, " ")
    .trim();

/** Below this, a topic match is too weak to be worth asserting. */
const MIN_TOPIC_SCORE = 3;

/**
 * Below this, a search hit is not worth offering as a suggestion.
 *
 * `scoreItem` awards a point for a bare substring overlap in either direction,
 * which is generous enough for a search box the visitor is watching but wrong
 * here: "what is the airspeed velocity of a swallow" scores against the tag
 * "ai" because "airspeed" contains it, and eBot would answer an unanswerable
 * question with a confident-looking link to the edge-AI page. Requiring more
 * than one incidental overlap keeps the fallback honest.
 */
const MIN_SEARCH_SCORE = 3;

/** Greetings get a greeting, not a search result for the word "hello". */
const GREETINGS =
  /^(hi|hey|hello|yo|howdy|greetings|good (morning|afternoon|evening)|thanks|thank you|ty|cheers|bye|goodbye)\b/;

/**
 * Answer a visitor's question from the knowledge base.
 *
 * Tries the curated topics first. Failing that, falls back to the site search
 * index so a question about any page still gets a useful pointer. Failing that
 * too, says plainly that it does not know — it never invents an answer.
 *
 * @param question Raw text as typed. Case and punctuation do not matter.
 * @returns The reply, any links to offer, and which of the three routes produced it.
 *
 * @example
 * answerQuestion("What boards does EmbeddedOS support?").kind;  // "topic"
 * answerQuestion("tell me about quantum computing").kind;       // "search"
 * answerQuestion("what is the airspeed of a swallow").kind;     // "unknown"
 */
export function answerQuestion(question: string): Answer {
  const q = normalise(question);

  if (!q) {
    return {
      reply:
        "Ask me anything about EmbeddedOS — the hardware it runs on, how to get started, or what the Foundation does.",
      links: [],
      kind: "unknown",
    };
  }

  if (GREETINGS.test(q) && q.split(" ").length <= 4) {
    return {
      reply:
        "Hello! Ask me about supported hardware, getting started, the health or aerospace research, licensing, or how to contribute.",
      links: [
        { label: "Getting started", href: "/getting-started" },
        { label: "What we build", href: "/products" },
      ],
      kind: "topic",
    };
  }

  const ranked = TOPICS.map(topic => ({ topic, score: scoreTopic(topic, q) }))
    .filter(t => t.score >= MIN_TOPIC_SCORE)
    .sort((a, b) => b.score - a.score);

  if (ranked.length > 0) {
    const { topic } = ranked[0];
    return { reply: topic.answer, links: topic.links ?? [], kind: "topic" };
  }

  // Nothing curated matched. The search index covers every page on the site, so
  // it can still point somewhere useful without asserting anything new.
  const { pages } = searchSite(question);
  const confident = pages.filter(p => p.score >= MIN_SEARCH_SCORE);
  if (confident.length > 0) {
    const top = confident.slice(0, 3);
    return {
      reply: `I don't have a prepared answer for that, but ${top.length === 1 ? "this page looks" : "these pages look"} relevant:`,
      links: top.map(p => ({ label: p.title, href: p.path })),
      kind: "search",
    };
  }

  return {
    reply:
      "I don't know that one — I only know what's published on this site, and I'd rather say so than guess.\n" +
      "\n" +
      "Try rephrasing, or email **contact@embeddedos.org** and a person will answer.",
    links: [
      { label: "FAQ", href: "/faq" },
      { label: "Documentation", href: "/docs" },
      { label: "Email contact@", href: "mailto:contact@embeddedos.org" },
    ],
    kind: "unknown",
  };
}
